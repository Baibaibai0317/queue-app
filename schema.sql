-- 在 Supabase SQL Editor 运行一次。需在 Authentication > Providers 开启 Anonymous Sign-Ins。
create table if not exists public.quyu_posts (
 id bigint generated by default as identity primary key,
 author_id uuid not null references auth.users(id),
 title text not null check (char_length(title) between 1 and 80),
 body text not null check (char_length(body) between 1 and 10000),
 category text not null,
 image_url text,
 created_at timestamptz not null default now()
);
create table if not exists public.quyu_likes (
 post_id bigint not null references public.quyu_posts(id) on delete cascade,
 user_id uuid not null references auth.users(id),
 created_at timestamptz not null default now(),
 primary key(post_id,user_id)
);
create table if not exists public.quyu_comments (
 id bigint generated by default as identity primary key,
 post_id bigint not null references public.quyu_posts(id) on delete cascade,
 user_id uuid not null references auth.users(id),
 body text not null check(char_length(body) between 1 and 1000),
 created_at timestamptz not null default now()
);
create index if not exists quyu_comments_post on public.quyu_comments(post_id);
create index if not exists quyu_likes_post on public.quyu_likes(post_id);
alter table public.quyu_posts enable row level security;
alter table public.quyu_likes enable row level security;
alter table public.quyu_comments enable row level security;
create policy "posts readable" on public.quyu_posts for select to authenticated using(true);
create policy "posts owner insert" on public.quyu_posts for insert to authenticated with check(author_id=auth.uid());
create policy "posts owner delete" on public.quyu_posts for delete to authenticated using(author_id=auth.uid());
create policy "likes readable" on public.quyu_likes for select to authenticated using(true);
create policy "likes self insert" on public.quyu_likes for insert to authenticated with check(user_id=auth.uid());
create policy "likes self delete" on public.quyu_likes for delete to authenticated using(user_id=auth.uid());
create policy "comments readable" on public.quyu_comments for select to authenticated using(true);
create policy "comments self insert" on public.quyu_comments for insert to authenticated with check(user_id=auth.uid());
create policy "comments self delete" on public.quyu_comments for delete to authenticated using(user_id=auth.uid());
insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
values('quyu-images','quyu-images',true,5242880,array['image/jpeg','image/png','image/webp'])
on conflict(id) do nothing;
